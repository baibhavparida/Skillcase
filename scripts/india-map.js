// Builds src/data/indiaMap.js, a flat map of India's states, from DataMeet's
// state boundaries (CC BY 4.0), which follow the Survey of India's official
// boundary. Download the five States/Admin2.* files from
// https://github.com/datameet/maps/tree/master/States into a folder, then
// run: node scripts/india-map.js <folder>
//
// The map uses a Lambert conformal conic projection, like Indian school maps.
// Borders between states are simplified once and shared (map-tools.js), so
// neighbours meet without gaps. Islands too small to draw become dots
// (Lakshadweep) or are dropped (the smallest Andaman, Nicobar and Sundarbans
// islands). This is the Learner Stories hero's map (LearnerMap.jsx).
import { writeFileSync } from "node:fs";
import path from "node:path";
import { groupStates, openRings, pathData, pinFor, readDbf, readShp, simplifyRings, stateId } from "./map-tools.js";

const source = path.join(process.argv[2] || ".", "Admin2");
const WIDTH = 1000;
const TOLERANCE = 2; // map units (the map is 1000 wide)
const MIN_AREA = 6; // smaller islands are dropped (or drawn as dots)

// Lambert conformal conic, standard parallels 12°N and 28°N, centred on 80°E.
const rad = Math.PI / 180;
const [phi1, phi2, lambda0] = [12 * rad, 28 * rad, 80 * rad];
const t = (phi) => Math.tan(Math.PI / 4 + phi / 2);
const n = Math.log(Math.cos(phi1) / Math.cos(phi2)) / Math.log(t(phi2) / t(phi1));
const F = (Math.cos(phi1) * t(phi1) ** n) / n;
function project([lon, lat]) {
  const rho = F / t(lat * rad) ** n;
  const theta = n * (lon * rad - lambda0);
  return [rho * Math.sin(theta), rho * Math.cos(theta)]; // y grows southwards
}

const rows = readDbf(`${source}.dbf`);
const rings = openRings(readShp(`${source}.shp`));

// Scale so the map is WIDTH units wide.
let [minX, minY, maxX, maxY] = [Infinity, Infinity, -Infinity, -Infinity];
for (const ring of rings) {
  for (const [x, y] of ring.points.map(project)) {
    [minX, minY, maxX, maxY] = [Math.min(minX, x), Math.min(minY, y), Math.max(maxX, x), Math.max(maxY, y)];
  }
}
const scale = WIDTH / (maxX - minX);
const HEIGHT = Math.ceil((maxY - minY) * scale);
const toMap = (point) => {
  const [x, y] = project(point);
  return [(x - minX) * scale, (y - minY) * scale];
};

const { byState, islands } = groupStates(rows, simplifyRings(rings, toMap, TOLERANCE), MIN_AREA);
const states = rows
  .map((row, i) => ({ name: row.ST_NM.replace(/ & /g, " and "), polygons: byState[i] }))
  .filter((state) => state.polygons.length)
  .map(({ name, polygons }) => ({ id: stateId(name), name, pin: pinFor(polygons), d: pathData(polygons) }))
  .sort((a, b) => a.pin[1] - b.pin[1]); // north to south

const banner = `// Generated by scripts/india-map.js from DataMeet's state boundaries
// (https://github.com/datameet/maps, CC BY 4.0, credited on the map), which
// follow the Survey of India's official boundary. Don't edit by hand: rerun
// the script. States are listed north to south; \`pin\` is a point well
// inside each state.
`;
const body = `export const indiaMap = ${JSON.stringify({ width: WIDTH, height: HEIGHT, states, islands })};\n`;
writeFileSync("src/data/indiaMap.js", banner + body);
console.log(`${states.length} states, ${islands.length} island dots, ${(body.length / 1024).toFixed(1)} KB`);
